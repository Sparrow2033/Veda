    @NonNull
    public static DemoLibrarySeed load(@NonNull Context context) {
        List<DemoSubjectSeed> subjects = buildSubjects();
        List<DemoNoteSeed> notes = buildNotes();

        validate(subjects, notes);
        return new DemoLibrarySeed(2, subjects, notes);
    }

    @NonNull
    private static List<DemoSubjectSeed> buildSubjects() {
        List<DemoSubjectSeed> out = new ArrayList<>();
        out.add(new DemoSubjectSeed("math", "Математика", "#5E88B8"));
        out.add(new DemoSubjectSeed("physics", "Физика", "#7A64C8"));
        out.add(new DemoSubjectSeed("informatics", "Информатика", "#4EA886"));
        out.add(new DemoSubjectSeed("biology", "Биология", "#5C9B63"));
        out.add(new DemoSubjectSeed("chemistry", "Химия", "#C07A52"));
        return out;
    }

    @NonNull
    private static List<DemoNoteSeed> buildNotes() {
        List<DemoNoteSeed> out = new ArrayList<>();

        addCluster(out, "math", "математика", mathSpecs());
        addCluster(out, "physics", "физика", physicsSpecs());
        addCluster(out, "informatics", "информатика", informaticsSpecs());
        addCluster(out, "biology", "биология", biologySpecs());
        addCluster(out, "chemistry", "химия", chemistrySpecs());

        return out;
    }

    private static void addCluster(@NonNull List<DemoNoteSeed> out,
                                   @NonNull String subjectSlug,
                                   @NonNull String subjectTag,
                                   @NonNull Spec[] specs) {
        if (specs.length == 0) return;

        String hubSlug = specs[0].slug;

        for (int i = 0; i < specs.length; i++) {
            Spec spec = specs[i];
            Set<String> links = new LinkedHashSet<>();

            if (i > 0) links.add(specs[i - 1].slug);
            if (i < specs.length - 1) links.add(specs[i + 1].slug);

            if (!spec.slug.equals(hubSlug)) {
                links.add(hubSlug);
            } else {
                for (int j = 1; j < Math.min(specs.length, 6); j++) {
                    links.add(specs[j].slug);
                }
            }

            links.addAll(Arrays.asList(spec.extraLinks));
            links.remove(spec.slug);

            List<String> tags = new ArrayList<>();
            tags.add(DEMO_SERVICE_TAG);
            tags.add(subjectTag);
            tags.addAll(Arrays.asList(spec.tags));

            List<String> body = new ArrayList<>();
            body.add(spec.summary);
            body.add(spec.bridge);

            out.add(new DemoNoteSeed(
                    spec.slug,
                    spec.title,
                    subjectSlug,
                    tags,
                    body,
                    new ArrayList<>(links)
            ));
        }
    }

