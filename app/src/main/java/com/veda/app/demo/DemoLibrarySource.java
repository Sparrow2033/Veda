    private static void validate(@NonNull List<DemoSubjectSeed> subjects,
                                 @NonNull List<DemoNoteSeed> notes) {
        Set<String> subjectSlugs = new LinkedHashSet<>();
        for (DemoSubjectSeed subject : subjects) {
            if (subject.slug == null || subject.slug.trim().isEmpty()) {
                throw new IllegalStateException("Пустой subject slug");
            }
            if (!subjectSlugs.add(normalize(subject.slug))) {
                throw new IllegalStateException("Повторяющийся subject slug: " + subject.slug);
            }
        }

        Set<String> noteSlugs = new LinkedHashSet<>();
        for (DemoNoteSeed note : notes) {
            if (note.slug == null || note.slug.trim().isEmpty()) {
                throw new IllegalStateException("Пустой note slug");
            }

            if (!subjectSlugs.contains(normalize(note.subjectSlug))) {
                throw new IllegalStateException("Заметка " + note.slug + " ссылается на неизвестный subjectSlug: " + note.subjectSlug);
            }

            if (!noteSlugs.add(normalize(note.slug))) {
                throw new IllegalStateException("Повторяющийся note slug: " + note.slug);
            }

            if (!note.tags.contains(DEMO_SERVICE_TAG)) {
                throw new IllegalStateException("У демо-заметки " + note.slug + " отсутствует служебный тег " + DEMO_SERVICE_TAG);
            }

            if (note.bodyParagraphs.isEmpty()) {
                throw new IllegalStateException("У демо-заметки " + note.slug + " пустое содержимое");
            }

            if (note.linkSlugs.isEmpty()) {
                throw new IllegalStateException("У демо-заметки " + note.slug + " нет связей");
            }
        }

        for (DemoNoteSeed note : notes) {
            for (String linkSlug : note.linkSlugs) {
                if (!noteSlugs.contains(normalize(linkSlug))) {
                    throw new IllegalStateException("Заметка " + note.slug + " ссылается на неизвестный link slug: " + linkSlug);
                }
                if (normalize(note.slug).equals(normalize(linkSlug))) {
                    throw new IllegalStateException("Заметка " + note.slug + " не должна ссылаться сама на себя");
                }
            }
        }

        if (notes.size() < 120) {
            throw new IllegalStateException("Демо-библиотека слишком маленькая: " + notes.size());
        }
    }

    @NonNull
    private static Spec c(@NonNull String slug,
                          @NonNull String title,
                          @NonNull String summary,
                          @NonNull String bridge,
                          @NonNull String[] tags,
                          @NonNull String... extraLinks) {
        return new Spec(slug, title, summary, bridge, tags, extraLinks);
    }

    @NonNull
    private static String normalize(@NonNull String value) {
        return value.trim().toLowerCase(Locale.ROOT);
    }

    private static final class Spec {
        final String slug;
        final String title;
        final String summary;
        final String bridge;
        final String[] tags;
        final String[] extraLinks;

        Spec(@NonNull String slug,
             @NonNull String title,
             @NonNull String summary,
             @NonNull String bridge,
             @NonNull String[] tags,
             @NonNull String[] extraLinks) {
            this.slug = slug;
            this.title = title;
            this.summary = summary;
            this.bridge = bridge;
            this.tags = tags;
            this.extraLinks = extraLinks;
        }
    }
